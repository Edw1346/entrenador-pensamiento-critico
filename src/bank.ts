const opts = (texts: string[]): Option[] =>
  texts.map((text, i) => ({ id: "abcd"[i], text }));
const rubric = (criteria: [string, string, string]): RubricCriterion[] =>
  criteria.map((description, i) => ({
    id: `r${i + 1}`,
    label: [
      "Conclusión y alcance",
      "Razonamiento y evidencia",
      "Límites y alternativas",
    ][i],
    description,
  }));
const base = (
  skill: SkillId,
  n: number,
  title: string,
  objective: string,
  prompt: string,
  modelAnswer: string,
  explanation: string,
  errors: string[],
  harder: string,
  criteria: [string, string, string],
) => ({
  id: `${skill}-${n}`,
  skill,
  title,
  objective,
  prompt: `Situación hipotética. ${prompt}`,
  modelAnswer,
  explanation,
  commonErrors: errors,
  harderVariant: harder,
  rubric: rubric(criteria),
  family: `${skill}-${n}`,
});
const C = (
  skill: SkillId,
  n: 1 | 2,
  title: string,
  objective: string,
  prompt: string,
  choices: string[],
  answer: string,
  model: string,
  explanation: string,
  errors: string[],
  harder: string,
  criteria: [string, string, string],
): Exercise => ({
  ...base(
    skill,
    n,
    title,
    objective,
    prompt,
    model,
    explanation,
    errors,
    harder,
    criteria,
  ),
  kind: "choice",
  difficulty: n,
  options: opts(choices),
  answer,
});
const step = (
  prompt: string,
  choices: string[],
  answer: string,
  explanation: string,
): ExerciseStep => ({ prompt, options: opts(choices), answer, explanation });
